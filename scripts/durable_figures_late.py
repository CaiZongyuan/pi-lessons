        mdfile = next(folder.glob('*.md'))
        md = mdfile.read_text()
        for order, m in enumerate(re.finditer(r'!\[[^\]]*\]\(([^)]+)\)', md), 1):
            id = f'D.{ch}.{order}'
            img = folder / unquote(m[1])
            after = md[m.end():].lstrip()
